def render_techtree_section(civ_token, techtree_by_civ, strings):
    """Section L — tech tree entries attributed to this civ."""
    techs = techtree_by_civ.get(civ_token, [])
    count = len(techs)

    parts = [
        f'<details class="cov-details cov-details-outer">'
        f'<summary class="cov-group-lbl cov-summary-row">'
        f'Per-civ tech tree entries'
        f'<span class="cov-count-pill">{count}</span></summary>'
    ]

    if not techs:
        parts.append('<div class="cov-row"><em class="cov-empty">(none)</em></div>')
    else:
        for tech in techs:
            name = tech.get("name") or tech.get("Name") or "?"
            # DisplayNameID child (case-insensitive tag)
            display_name_id = ""
            for child in tech:
                if child.tag.lower() == "displaynameid":
                    display_name_id = (child.text or "").strip()
                    break
            display_name = strings.get(display_name_id, "") if display_name_id else ""

            # Effects summary
            effects_el = None
            for child in tech:
                if child.tag.lower() == "effects":
                    effects_el = child
                    break
            effect_list = list(effects_el) if effects_el is not None else []
            effect_types = []
            for e in effect_list:
                etype = e.get("type") or e.get("Type") or "?"
                if etype not in effect_types:
                    effect_types.append(etype)
            n_effects = len(effect_list)
            effect_summary = ", ".join(effect_types[:6])
            if len(effect_types) > 6:
                effect_summary += ", ..."

            name_esc = html_module.escape(name)
            dn_esc = html_module.escape(display_name)
            summary_esc = html_module.escape(f"{n_effects} effects: {effect_summary}" if effect_summary else f"{n_effects} effects")

            parts.append(
                f'<details class="cov-row">'
                f'<summary>'
                f'<code class="cov-path">{name_esc}</code>'
                + (f'&nbsp;<span class="cov-string-text">{dn_esc}</span>' if display_name else '')
                + f'&nbsp;<span class="cov-na">({summary_esc})</span>'
                f'</summary>'
            )
            # Inline effect details
            for e in effect_list:
                attribs = " ".join(
                    f'{html_module.escape(k)}="{html_module.escape(v)}"'
                    for k, v in e.attrib.items()
                )
                target_text = ""
                target_el = e.find("Target")
                if target_el is None:
                    target_el = e.find("target")
                if target_el is not None:
                    target_text = (target_el.text or "").strip()
                parts.append(
                    f'<div class="cov-row" style="padding-left:1em;font-size:11px;">'
                    f'<code class="cov-path">{attribs}</code>'
                    + (f'&nbsp;<span class="cov-lbl">{html_module.escape(target_text)}</span>' if target_text else '')
                    + f'</div>'
                )
            parts.append('</details>')  # end tech row

    parts.append('</details>')  # end outer
    return "".join(parts), count


