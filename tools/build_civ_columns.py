# ── Age-up choices collector ───────────────────────────────────────────────────
# Politician tech names that contain these keywords → age tier
_POLITICIAN_AGE_KEYWORDS = [
    # (keyword_in_techname_lower, age_label)
    ("colonial",   "Age II — Colonial"),
    ("fortress",   "Age III — Fortress"),
    ("industrial", "Age IV — Industrial"),
    ("imperial",   "Age V — Imperial"),
]
# Basenames that are shared generic politicians, not civ-specific unlocks
_POLITICIAN_GENERIC_PREFIXES = (
    "Politician", "DEPolitician", "UnlockPolitician",
)


def _politician_age_tier(tech_name: str) -> str:
    """Guess the age tier of a politician tech from its tech name."""
    n = tech_name.lower()
    for keyword, label in _POLITICIAN_AGE_KEYWORDS:
        if keyword in n:
            return label
    # Fallback: generals / viceroys / black duke are Industrial+
    if any(x in n for x in ("viceroy", "general", "blackduke", "kingsmusketeer")):
        return "Age IV — Industrial"
    # Mohawk, Engineer, Bishop, Admiral → Fortress
    if any(x in n for x in ("mohawk", "engineer", "bishop", "admiral", "merccontractor")):
        return "Age III — Fortress"
    # Logistician, PhilosopherPrince, Naturalist, Governor → Colonial
    if any(x in n for x in ("logistician", "philosopher", "naturalist", "governor", "inventor")):
        return "Age II — Colonial"
    return "Age II — Colonial"  # safe default


def _politician_display_name(tech_name: str) -> str:
    """Convert a politician tech name to a human-readable label.

    Strips common prefixes and the civ-specific suffix, then title-cases.
    E.g. DEPoliticianLogisticianColonialBritish -> Logistician (Colonial)
         UnlockPoliticianMohawkStatesmanBritish -> Mohawk Statesman
         PoliticianViceroyBritish               -> Viceroy
    """
    n = tech_name
    for prefix in ("DEPolitician", "UnlockPolitician", "Politician"):
        if n.startswith(prefix):
            n = n[len(prefix):]
            break
    # Strip civ-specific suffix (British, French, Spanish, etc.).
    # Order longest-first so "Ottomans" wins over "Ottoman" when present.
    for civ_suffix in (
        "FederalMX", "SouthAfricans", "FrenchCanadians",
        "British", "French", "Spanish", "Portuguese", "Dutch", "Germans",
        "German", "Russians", "Russian", "Ottomans", "Ottoman",
        "Italians", "Italian", "Maltese", "Swedish", "Swedes", "Chinese",
        "Japanese", "Indians", "Indian", "Aztecs", "Aztec", "Iroquois",
        "Inca", "Sioux", "Lakota",
        "Americans", "American", "Mexicans", "Mexican", "Ethiopians",
        "Ethiopian", "Hausa", "Egyptians", "Egyptian", "Brazilians",
        "Brazilian", "Brazil",
        "Argentines", "Chileans", "Peruvians", "Columbians", "Haitians",
        "Indonesians", "Finnish", "Mayans", "Barbary", "Canadians",
        "Hungarians", "Romanians", "Texians",
        "MX",
    ):
        if n.endswith(civ_suffix):
            n = n[: -len(civ_suffix)]
            break
    # Insert spaces before capital letters (CamelCase -> words)
    words = re.sub(r"([A-Z][a-z])", r" \1", n).strip()
    # Collapse double spaces
    words = re.sub(r"\s+", " ", words).strip()
    return words if words else tech_name


def collect_age_ups_for_civ(civ_token: str, techtree_xml_path: str) -> list:
    """Parse techtreemods.xml and return age-up politician entries for a civ.

    Returns a list of dicts: {tech_name, display_name, age_tier}.

    Strategy
    --------
    1. Primary: scan ALL Tech elements for TechStatus=obtainable effects
       whose text (a) contains "Politician" and (b) ends with the civ stem
       (e.g. "British" → DEPoliticianLogisticianColonialBritish).
       These are civ-specific politician unlocks.
    2. Fallback: if the civ has no civ-specific politicians, look for techs
       that activate Colonialize<Stem>, Fortressize<Stem>, Industrialize<Stem>
       and harvest the generic Politician entries in those same techs.
    """
    # Derive the civ base stem (e.g. "British" from "ANWBritish")
    civ_stem = civ_token
    for prefix in ("ANW", "DE", "XP"):
        if civ_stem.startswith(prefix):
            civ_stem = civ_stem[len(prefix):]
            break
    civ_stem_lower = civ_stem.lower()

    # Allow alternative stems where the tech_name suffix differs from the
    # token stem (e.g. ANWOttomans → tech names end with "Ottoman" singular,
    # ANWSwedes → "Swedish" adjective, ANWMexicans → "MX" / "FederalMX",
    # ANWEthiopians → "Ethiopian" singular). The parser accepts a match
    # against any stem alias.
    _STEM_ALIASES = {
        "ottomans":   ["ottoman"],
        "italians":   ["italian"],
        "swedes":     ["swedish"],
        "germans":    ["german"],
        "russians":   ["russian"],
        "mexicans":   ["mx", "federalmx", "mexican"],
        "ethiopians": ["ethiopian"],
        "americans":  ["american"],
        "egyptians":  ["egyptian"],
        "brazilians": ["brazilian", "brazil"],
        "indians":    ["indian"],
        "aztecs":     ["aztec"],
    }
    civ_stems_lower = [civ_stem_lower] + _STEM_ALIASES.get(civ_stem_lower, [])

    try:
        tree = ET.parse(techtree_xml_path)
        root = tree.getroot()
    except Exception:
        return []

    politicians: list = []
    seen: set = set()

    techs = root.findall(".//Tech") + root.findall(".//tech")

    # Pass 1: civ-specific politician entries (tech name ends with civ stem)
    for tech in techs:
        for child in tech:
            if child.tag.lower() != "effects":
                continue
            for e in child:
                if (e.get("type") or e.get("Type") or "").lower() != "techstatus":
                    continue
                status = (e.get("status") or e.get("Status") or "").lower()
                if status != "obtainable":
                    continue
                t = (e.text or "").strip()
                t_lower = t.lower()
                # Must contain "politician" and end with the civ stem (or alias)
                if (
                    "politician" in t_lower
                    and any(t_lower.endswith(s) for s in civ_stems_lower)
                    and t not in seen
                ):
                    seen.add(t)
                    politicians.append({
                        "tech_name":    t,
                        "display_name": _politician_display_name(t),
                        "age_tier":     _politician_age_tier(t),
                    })

    if politicians:
        return politicians

    # Pass 2 fallback: find activator techs and harvest generic politician entries
    # (useful for civs that use vanilla politician menu unchanged). Accept the
    # `DEColonialize<Stem>` / `ANWColonialize<Stem>` prefixes as well — many
    # ANW/DLC civs use those variants for their age-up activator tech names.
    # Activator base names. We match by substring (case-insensitive) so that
    # variants like "ANWFortressizeEgyptiansShadow" or "ANWAge0Maya" still
    # register. Also include "age0", "age2", … pattern for ANW start techs.
    _ACTIVATOR_VERBS = ("colonialize", "fortressize", "industrialize",
                        "age0", "age2", "age3", "age4", "age5")
    # Special token stems for civs whose internal naming differs from the
    # civ_token stem (e.g. ANWMayans → "maya", ANWTexians → "texas").
    _ANW_INTERNAL_STEM = {
        "mayans":  ["maya"],
        "texians": ["texas"],
        "barbary": ["morocco"],
    }
    extra_stems = _ANW_INTERNAL_STEM.get(civ_stem_lower, [])
    all_stems = civ_stems_lower + extra_stems

    activator_substrings = set()
    for stem in all_stems:
        for verb in _ACTIVATOR_VERBS:
            activator_substrings.add(f"{verb}{stem}")

    for tech in techs:
        activates_this_civ = False
        effects_el = None
        for child in tech:
            if child.tag.lower() == "effects":
                effects_el = child
                break
        if effects_el is None:
            continue
        # Match against either: (a) effect text equals an activator name, or
        # (b) the parent tech's own name contains an activator substring.
        tech_name_lower = (tech.get("name") or tech.get("Name") or "").lower()
        if any(sub in tech_name_lower for sub in activator_substrings):
            activates_this_civ = True
        if not activates_this_civ:
            for e in effects_el:
                if (e.get("type") or e.get("Type") or "").lower() == "techstatus":
                    t = (e.text or "").strip().lower()
                    if any(sub in t for sub in activator_substrings):
                        activates_this_civ = True
                        break
        if not activates_this_civ:
            continue
        for e in effects_el:
            if (e.get("type") or e.get("Type") or "").lower() != "techstatus":
                continue
            status = (e.get("status") or e.get("Status") or "").lower()
            if status != "obtainable":
                continue
            t = (e.text or "").strip()
            t_lower = t.lower()
            if "politician" in t_lower and t not in seen:
                seen.add(t)
                politicians.append({
                    "tech_name":    t,
                    "display_name": _politician_display_name(t),
                    "age_tier":     _politician_age_tier(t),
                })

    # Pass 3 fallback: federal politicians keyed by prefix rather than suffix
    # (e.g. DEPoliticianFederalMX* are Mexican federal politicians keyed by
    # state name, not by a "Mexican" suffix).
    _PREFIX_BUCKETS = {
        "mexicans": "DEPoliticianFederalMX",
    }
    if not politicians:
        bucket_prefix = _PREFIX_BUCKETS.get(civ_stem_lower)
        if bucket_prefix:
            for tech in techs:
                tname = tech.get("name") or tech.get("Name") or ""
                if not tname.startswith(bucket_prefix):
                    continue
                if tname not in seen:
                    seen.add(tname)
                    politicians.append({
                        "tech_name":    tname,
                        "display_name": _politician_display_name(tname),
                        "age_tier":     _politician_age_tier(tname),
                    })

    return politicians


