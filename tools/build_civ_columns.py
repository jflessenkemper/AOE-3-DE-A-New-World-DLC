def load_techtree_by_civ():
    """Return dict civ_token -> list of tech Element objects.

    A tech is attributed to a civ if its name contains the civ stem
    (without ANW prefix) case-insensitively.  The 44-civ token list is
    consulted so we don't false-positive on short stems.
    """
    path = os.path.join(DATA_DIR, "techtreemods.xml")
    tree = ET.parse(path)
    root = tree.getroot()
    techs = root.findall(".//Tech") + root.findall(".//tech")

    # Build set of ANW civ stems (lowercase, no ANW prefix) and the
    # full tokens so we can do exact-prefix matching on tech names.
    civ_path = os.path.join(DATA_DIR, "playercolors.xml")
    ctree = ET.parse(civ_path)
    all_tokens = [c.get("civ") for c in ctree.getroot().findall(".//Color") if c.get("civ")]
    anw_tokens = [t for t in all_tokens if t.startswith("ANW")]

    result = {tok: [] for tok in all_tokens}

    for tech in techs:
        name = tech.get("name") or tech.get("Name") or ""
        if not name:
            continue
        name_lower = name.lower()
        matched = set()
        # Match by ANW-token name prefix: e.g. ANWBrazil -> "anwbrazil"
        for tok in anw_tokens:
            tok_lower = tok.lower()
            if name_lower.startswith(tok_lower):
                matched.add(tok)
        # Also search for non-ANW civ stems in name (for base civs)
        for tok in all_tokens:
            if tok in matched:
                continue
            stem = tok.lower()
            for pf in ("anw", "de", "xp"):
                if stem.startswith(pf):
                    stem = stem[len(pf):]
                    break
            if len(stem) >= 4 and stem in name_lower:
                matched.add(tok)
        for tok in matched:
            if tok in result:
                result[tok].append(tech)

    return result

def load_personality(civ_name):
    """Load rushboom value from .personality file."""
    # Normalise civ_name to filename: remove prefix ANW/DE/XP, lowercase
    lower = civ_name.lower()
    for prefix in ("anw", "de", "xp"):
        if lower.startswith(prefix):
            lower = lower[len(prefix):]
            break
    # Map singular base-civ stems → ANW plural filenames where they
    # differ (anwaztecs vs xpaztec, anwhaudenosaunee vs xpiroquois,
    # anwlakota vs xpsioux, anwusa vs deamericans, anwswedes vs deswedish).
    aliases = {
        "aztec":      "aztecs",
        "iroquois":   "haudenosaunee",
        "sioux":      "lakota",
        "americans":  "usa",
        "swedish":    "swedes",
    }
    stems = [aliases.get(lower, lower)]
    if lower in aliases:
        stems.append(lower)  # also try the original
    candidates = []
    for stem in stems:
        candidates.append(f"anw{stem}.personality")
        candidates.append(f"{stem}.personality")
    for fname in candidates:
        path = os.path.join(GAME_DIR, "ai", fname)
        if os.path.exists(path):
            with open(path) as f:
                content = f.read()
            m = re.search(r"<rushboom>(-?\d+)</rushboom>", content)
            if m:
                val = int(m.group(1))
                label = {0: "Boom", 1: "Rush", 2: "Balanced",
                         -1: "(unset)"}.get(val, str(val))
                return label, fname
            return "?", fname
    return "?", None

