def _is_vanilla_asset_path(path):
    """True for paths that live in vanilla AoE3 DE's data/ tree (not in mod)."""
    p = (path or "").replace("\\", "/").lower().lstrip("/")
    return p.startswith(_VANILLA_ASSET_PREFIXES)


def collect_paths_for_civ(civ_token, civ_el, hc, art_inventory):
    """Return list of {label, path, exists} for every path declared for this civ.

    `exists` can be:
        True       — file shipped by this mod (green ✓)
        False      — declared but not found anywhere (red ✗ — real problem)
        "vanilla"  — vanilla AoE3 DE engine reference; not a mod file (gray ⊙)
        "engine"   — engine identifier (lightset / watertype / xsai), not a path

    Sources:
    1. civmods.xml: portrait/wpf/texture fields
    2. anwhomecity*.xml: scene, camera, sounds, lightset, watertype, buildings
    3. art_inventory.json art_surfaces
    4. AI personality file
    """
    rows = []
    seen_paths = set()

    def add(label, path, exists=None):
        if not path:
            return
        path = path.replace("\\", "/")
        key = (label, path)
        if key in seen_paths:
            return
        seen_paths.add(key)
        if exists is None:
            # Check on disk
            candidates = [
                os.path.join(MOD_ROOT, path),
                os.path.join(MOD_ROOT, "resources", path),
                os.path.join(MOD_ROOT, "data", path),
            ]
            exists = any(os.path.exists(c) for c in candidates)
            # If still not found in mod, classify as vanilla reference if the
            # path is a known vanilla AoE3 DE asset prefix.
            if exists is False and _is_vanilla_asset_path(path):
                exists = "vanilla"
        rows.append({"label": label, "path": path, "exists": exists})

    # ── 1. civmods.xml path fields ─────────────────────────────────────────────
    if civ_el is not None:
        add("HC flag (large WPF)",     civ_el.findtext("homecityflagiconwpf") or "")
        add("HC flag button",          civ_el.findtext("homecityflagbuttonwpf") or "")
        # homecityflagbuttonset(large) hold WPF resource-dictionary keys
        # (camelCase identifiers like "britishFlagBtn"), not file paths.
        for lbl, key in [
            ("HC flag button set (large)", "homecityflagbuttonsetlarge"),
            ("HC flag button set",         "homecityflagbuttonset"),
        ]:
            v = (civ_el.findtext(key) or "").strip()
            if v:
                add(lbl, v, exists="engine")
        add("HC flag texture (DDT)",   civ_el.findtext("homecityflagtexture") or "")
        add("HC lobby preview / portrait", civ_el.findtext("homecitypreviewwpf") or "")
        add("Postgame flag texture",   civ_el.findtext("postgameflagtexture") or "")
        add("Postgame flag WPF",       civ_el.findtext("postgameflagiconwpf") or "")
        add("Portrait object (world)", civ_el.findtext("portrait") or "")

        # HC XML filename
        hc_file = civ_el.findtext("homecityfilename") or ""
        if hc_file:
            add("HC XML", f"data/{hc_file}")

    # ── 2. art_inventory art_surfaces ─────────────────────────────────────────
    _SURFACE_LABELS = {
        "diplomacy_portrait_wpf":   "Diplomacy panel portrait",
        "scoreboard_portrait_wpf":  "Scoreboard portrait",
        "postgame_flag_wpf":        "Postgame flag WPF (art_inv)",
        "homecity_preview_wpf":     "HC preview portrait",
        "homecity_flag_icon_wpf":   "HC flag icon WPF (art_inv)",
        "homecity_flag_button_wpf": "HC flag button WPF (art_inv)",
        "homecity_filename":        "HC XML (art_inv)",
        "homecity_visual_scene":    "HC visual scene (art_inv)",
        "custom_leader_portrait_hires": "Leader high-res portrait",
    }
    inv_civ = art_inventory.get("civs", {}).get(civ_token, {})
    surfaces = inv_civ.get("art_surfaces", {})
    if isinstance(surfaces, dict):
        for surf_key, surf_val in surfaces.items():
            surf_path = ""
            if isinstance(surf_val, dict):
                surf_path = surf_val.get("path", "")
            elif isinstance(surf_val, str):
                surf_path = surf_val
            label_text = _SURFACE_LABELS.get(surf_key, surf_key.replace("_", " ").title())
            add(label_text, surf_path)

    # ── 3. homecity XML: scene + camera + audio + building paths ──────────────
    if hc is not None:
        # File-path fields (actually point to XML / .gr2 / .cam files on disk)
        scene_path_fields = [
            ("HC scene visual",      "visual"),
            ("HC water visual",      "watervisual"),
            ("HC background visual", "backgroundvisual"),
            ("HC path data (.gr2)",  "pathdata"),
            ("HC camera (.cam)",     "camera"),
            ("HC widescreen camera", "widescreencamera"),
            ("HC ambient sounds",    "ambientsounds"),
        ]
        for label_text, key in scene_path_fields:
            val = hc.get(key, "").strip()
            if val:
                # File-path fields. Mod-side disk check first; if missing AND
                # the path is a known vanilla prefix, fall back to "vanilla".
                disk_path = os.path.join(DATA_DIR, val.replace("\\", "/"))
                on_disk = os.path.exists(disk_path)
                if not on_disk and _is_vanilla_asset_path(val):
                    add(label_text, val, exists="vanilla")
                else:
                    add(label_text, val, exists=on_disk)

        # Engine identifier fields (NOT file paths — declarations like "London")
        engine_id_fields = [
            ("HC light set",             "lightset"),
            ("HC water type",            "watertype"),
            ("HC AI personality (xsai)", "xsai"),
        ]
        for label_text, key in engine_id_fields:
            val = hc.get(key, "").strip()
            if val:
                add(label_text, val, exists="engine")

    # HC buildings (portrait icons) — re-parse HC XML
    if civ_el is not None:
        hc_file = civ_el.findtext("homecityfilename") or ""
        if hc_file:
            hc_path = os.path.join(DATA_DIR, hc_file)
            if os.path.exists(hc_path):
                try:
                    hc_tree = ET.parse(hc_path)
                    hc_root = hc_tree.getroot()
                    for b in hc_root.findall("./building"):
                        bname = b.findtext("name") or "?"
                        portrait = b.findtext("portrait") or ""
                        if portrait:
                            # Building portraits are usually ui/home_city/* — vanilla refs
                            add(f"HC building portrait — {bname}", portrait)
                        cam = b.findtext("camera") or ""
                        if cam:
                            cam_disk = os.path.join(DATA_DIR, cam.replace("\\","/"))
                            cam_exists = os.path.exists(cam_disk)
                            if not cam_exists and _is_vanilla_asset_path(cam):
                                add(f"HC building camera — {bname}", cam, exists="vanilla")
                            else:
                                add(f"HC building camera — {bname}", cam, exists=cam_exists)
                        wcam = b.findtext("widescreencamera") or ""
                        if wcam and wcam != cam:
                            wcam_disk = os.path.join(DATA_DIR, wcam.replace("\\","/"))
                            wcam_exists = os.path.exists(wcam_disk)
                            if not wcam_exists and _is_vanilla_asset_path(wcam):
                                add(f"HC building widescreen cam — {bname}", wcam, exists="vanilla")
                            else:
                                add(f"HC building widescreen cam — {bname}", wcam, exists=wcam_exists)
                except ET.ParseError:
                    pass

    # ── 4. AI personality file ─────────────────────────────────────────────────
    stem = get_civ_stem(civ_token)
    pers_rel = f"game/ai/anw{stem}.personality"
    pers_full = os.path.join(MOD_ROOT, pers_rel)
    if os.path.exists(pers_full):
        add("AI personality file", pers_rel, exists=True)
    else:
        # Try the non-anw prefix variant
        for alias in _VANILLA_STEM_ALIAS.get(stem, [stem]):
            pers_alt = f"game/ai/anw{alias}.personality"
            if os.path.exists(os.path.join(MOD_ROOT, pers_alt)):
                add("AI personality file", pers_alt, exists=True)
                break
        else:
            add("AI personality file", pers_rel, exists=False)

    # ── 5. cpai_avatar portrait paths (PNG + DDT) ─────────────────────────────
    # The mod ships avatars under several stem flavours:
    #   - `cpai_avatar_anw{stem}.png` (most ANW civs: anwfrench, anwbarbary…)
    #   - `cpai_avatar_{stem}.png`    (historic bases: hausa, napoleonic_france…)
    #   - `cpai_avatar_{alias}.png`   (renamed stems: usa→united_states,
    #                                  napoleonicfrance→napoleonic_france)
    # We try every candidate stem; if any matches, mark green ✓. Otherwise
    # the path stays red ✗ so we can fix the underlying civmods reference.
    avatar_aliases = {
        "usa":              ["united_states", "anwusa"],
        "napoleonicfrance": ["napoleonic_france", "anwnapoleonicfrance"],
        "revfrance":        ["anwrevfrance"],
        "frenchcanadians":  ["french_canadians", "anwfrenchcanadians"],
        "swedes":           ["swedish", "anwswedes"],
        "iroquois":         ["haudenosaunee", "anwhaudenosaunee"],
        "sioux":            ["lakota", "anwsioux"],
        "aztec":            ["aztecs", "anwaztecs"],
        "americans":        ["united_states", "americans_jefferson"],
    }
    base_stem = stem
    stem_candidates = [f"anw{base_stem}", base_stem]
    for alt in avatar_aliases.get(base_stem, []):
        if alt not in stem_candidates:
            stem_candidates.append(alt)

    def _resolve_avatar(ext):
        for cand in stem_candidates:
            rel = f"{'resources/images/icons/singleplayer' if ext == 'png' else 'art/ui/singleplayer'}/cpai_avatar_{cand}.{ext}"
            if os.path.exists(os.path.join(MOD_ROOT, rel)):
                return rel, True
        # Default to the base-stem path so the "missing" label points at the
        # most-likely-expected filename.
        rel = f"{'resources/images/icons/singleplayer' if ext == 'png' else 'art/ui/singleplayer'}/cpai_avatar_{base_stem}.{ext}"
        return rel, False

    png_rel, png_found = _resolve_avatar("png")
    add("Default avatar PNG", png_rel, exists=png_found)
    ddt_rel, ddt_found = _resolve_avatar("ddt")
    add("Default avatar DDT (compiled)", ddt_rel, exists=ddt_found)

    # Per-leader variants — search across every candidate stem.
    # DDT is the compiled hot-path texture; the engine falls back to the PNG
    # if the DDT is absent, so a missing DDT alongside an existing PNG is
    # *cosmetic* (no in-game impact). We mark those rows as "optional"
    # rather than missing so the column report stays signal-only.
    portrait_dir = os.path.join(MOD_ROOT, "resources/images/icons/singleplayer")
    seen_leader = set()
    if os.path.isdir(portrait_dir):
        for cand in stem_candidates:
            prefix = f"cpai_avatar_{cand}_"
            for fn in sorted(os.listdir(portrait_dir)):
                if fn.startswith(prefix) and fn.endswith(".png"):
                    leader = fn[len(prefix):-4]
                    if leader in seen_leader:
                        continue
                    seen_leader.add(leader)
                    add(f"Leader portrait PNG — {leader}",
                        f"resources/images/icons/singleplayer/{fn}",
                        exists=True)
                    ddt_leader = f"art/ui/singleplayer/cpai_avatar_{cand}_{leader}.ddt"
                    ddt_full = os.path.join(MOD_ROOT, ddt_leader)
                    if os.path.exists(ddt_full):
                        add(f"Leader portrait DDT — {leader}", ddt_leader, exists=True)
                    else:
                        add(f"Leader portrait DDT — {leader}", ddt_leader, exists="optional")

    return rows


def render_paths_table(rows):
    """Render the Paths section as a two-column table."""
    parts = [
        f'<div class="paths-section">',
        f'<div class="section-label">Paths ({len(rows)})</div>',
        f'<table class="info-table path-table">',
        f'<tbody>',
    ]
    if not rows:
        parts.append('<tr><td colspan="2"><span class="empty">No paths found</span></td></tr>')
    else:
        for r in rows:
            lbl_esc  = html_module.escape(r["label"])
            path     = r["path"]
            exists   = r.get("exists", None)
            path_esc = html_module.escape(path)
            # Badge
            if exists is True:
                badge = '<span class="path-ok" title="shipped by this mod">&#10003;</span> '
            elif exists == "vanilla":
                badge = '<span class="path-vanilla" title="vanilla AoE3 DE engine reference; not shipped by this mod">&#9678;</span> '
            elif exists == "engine":
                badge = '<span class="path-engine" title="engine identifier (light set / water type / xsai), not a file path">&#9670;</span> '
            elif exists == "optional":
                badge = '<span class="path-optional" title="optional compiled-format companion (engine falls back to PNG)">&#9678;</span> '
            elif exists is False:
                badge = '<span class="path-missing-badge" title="declared but not found anywhere">&#10007;</span> '
            else:
                badge = ''
            parts.append(
                f'<tr>'
                f'<td class="lbl">{lbl_esc}</td>'
                f'<td class="mono"><code title="{path_esc}">{badge}{path_esc}</code></td>'
                f'</tr>'
            )
    parts += ['</tbody>', '</table>', '</div>']
    return "".join(parts)


