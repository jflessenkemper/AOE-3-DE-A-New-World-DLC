def build():
    print("Loading data sources...")
    strings = load_strings()
    civmods = load_civmods()
    colors  = load_playercolors()
    blurbs  = load_blurbs()
    spec    = load_playstyle_spec()
    decks   = load_decks()
    cards   = load_cards()
    print("Loading J/K/L data sources...")
    strings_by_civ  = load_strings_by_civ()
