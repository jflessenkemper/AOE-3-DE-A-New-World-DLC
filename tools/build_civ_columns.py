# ── Playstyle spec lookup ──────────────────────────────────────────────────────
# Explicit civ-token → spec civ_label aliases for civs whose tokens don't match
# the spec's spaced civ_label. Without these, find_spec_entry returns None and
# the rendered Doctrine / Doctrine summary fall back to "—" placeholders.
SPEC_LABEL_ALIASES = {
    "usa":              "United States",
    "revfrance":        "Revolutionary France",
    "napoleonicfrance": "Napoleonic France",
    "southafricans":    "South Africans",
    "french":           "French Louis",
}

def find_spec_entry(civ_token, spec):
    """Try to find a matching playstyle spec entry for a civ token."""
    # The spec uses human-readable keys like 'Hungarians Kossuth Revolution'
    b_key = blurb_key(civ_token)
    base = b_key[3:] if b_key.startswith("ANW") else b_key
    base_lower = base.lower()
    base_nospace = base_lower.replace(" ", "")

    target_label = SPEC_LABEL_ALIASES.get(base_nospace)
    if target_label:
        for key, val in spec.items():
            if isinstance(val, dict) and val.get("civ_label") == target_label:
                return val, key

    for key, val in spec.items():
        if not isinstance(val, dict):
            continue
        civ_label = val.get("civ_label", "")
        civ_label_lower = civ_label.lower()
        if civ_label_lower == base_lower:
            return val, key
        if civ_label_lower.replace(" ", "") == base_nospace:
            return val, key

    # Loose fallback: substring match against key, but only if civ_label is
    # itself a prefix of base or vice versa (avoids spurious matches like
    # base="indians" hitting key "Indonesians …").
    for key, val in spec.items():
        if not isinstance(val, dict):
            continue
        civ_label_lower = val.get("civ_label", "").lower()
        if civ_label_lower and (
            civ_label_lower.startswith(base_lower)
            or base_lower.startswith(civ_label_lower)
        ):
            return val, key
    return None, None

# ── Colour helpers ─────────────────────────────────────────────────────────────
def luminance(r, g, b):
    def c(x):
        x /= 255
        return x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4
    return 0.2126 * c(r) + 0.7152 * c(g) + 0.0722 * c(b)

def text_color(r, g, b):
    return "#fff" if luminance(r, g, b) < 0.35 else "#111"

def bg_style(r, g, b):
    return (
        f"background:linear-gradient(160deg,"
        f"rgb({r},{g},{b}) 0%,"
        f"rgb({max(r-30,0)},{max(g-30,0)},{max(b-30,0)}) 100%);"
    )

# ── Section J: All civ-tagged strings ─────────────────────────────────────────
def render_strings_section(civ_token, strings_by_civ):
    """Section J — all civ-tagged strings from stringmods.xml for this civ."""
    # Try the token directly; also try with/without ANW prefix
    entries = strings_by_civ.get(civ_token, [])
    if not entries:
        # Some markers use bare token without "ANW" prefix — try it
        bare = civ_token[3:] if civ_token.startswith("ANW") else civ_token
        entries = strings_by_civ.get(bare, [])

    count = len(entries)
    parts = [
        f'<details class="cov-details cov-details-outer">'
        f'<summary class="cov-group-lbl cov-summary-row">'
        f'All civ-tagged strings'
        f'<span class="cov-count-pill">{count}</span></summary>'
    ]
    if not entries:
        parts.append('<div class="cov-row"><em class="cov-empty">(none)</em></div>')
    else:
        for loc_id, text in entries:
            display = text if len(text) <= 200 else text[:197] + "..."
            parts.append(
                f'<div class="cov-row">'
                f'<code class="cov-path">{html_module.escape(loc_id)}</code>'
                f'&nbsp;<span class="cov-string-text" title="{html_module.escape(text)}">'
                f'{html_module.escape(display)}</span>'
                f'</div>'
            )
    parts.append('</details>')
    return "".join(parts), count


# ── Section K: All art asset references ───────────────────────────────────────
def render_art_refs_section(civ_token, civ_el):
    """Section K — every art-referencing element in civmods.xml + homecity XML."""
    ART_SUFFIXES = ('.png', '.ddt', '.gr2', '.tga', '.xml', '.wpf', '.xaml',
                    '.jpg', '.jpeg', '.webp')

    def _is_art(val):
        v = (val or "").strip().lower()
        return any(v.endswith(s) for s in ART_SUFFIXES)

    def _is_art_tag(tag):
        t = tag.lower()
        return (t.endswith('filename') or t.endswith('texture') or
                t.endswith('icon') or t.endswith('portrait') or
                t.endswith('wpf') or t.endswith('visual') or
                t.endswith('scene') or t.endswith('music'))

    # --- civmods.xml block ---
    civmods_rows = []
    if civ_el is not None:
        for elem in civ_el.iter():
            tag = elem.tag
            text = (elem.text or "").strip()
            # Emit if tag name suggests art OR text looks like an art path
            if (_is_art_tag(tag) or _is_art(text)) and text:
                civmods_rows.append((tag, text))
            # Check attributes
            for attr, val in elem.attrib.items():
                if _is_art(val):
                    civmods_rows.append((f'{tag}@{attr}', val))

    # --- homecity XML: scene refs (top-level elements) ---
    hc_scene_rows = []
    # --- homecity XML: unit/building file refs ---
    hc_unit_rows = []

    hc_filename = civ_el.findtext("homecityfilename") if civ_el is not None else ""
    if hc_filename:
        hc_path = os.path.join(DATA_DIR, hc_filename)
        if os.path.exists(hc_path):
            try:
                hc_tree = ET.parse(hc_path)
                hc_root = hc_tree.getroot()
                for elem in hc_root.iter():
                    tag = elem.tag
                    text = (elem.text or "").strip()
                    parent = None  # we'll find parent via traversal below
                    if _is_art(text) or _is_art_tag(tag):
                        if text:
                            # Classify: direct children of root = scene refs,
                            # descendants of <building> = unit refs
                            hc_scene_rows.append((tag, text))
                    for attr, val in elem.attrib.items():
                        if _is_art(val):
                            hc_scene_rows.append((f'{tag}@{attr}', val.strip()))
                # Separate building-file rows from scene rows
                for b in hc_root.findall(".//building"):
                    for elem in b.iter():
                        tag = elem.tag
                        text = (elem.text or "").strip()
                        if text and (_is_art(text) or _is_art_tag(tag)):
                            key = (tag, text)
                            if key in [(r[0], r[1]) for r in hc_scene_rows]:
                                hc_scene_rows.remove(key)
                            hc_unit_rows.append(key)
                        for attr, val in elem.attrib.items():
                            if _is_art(val):
                                key2 = (f'{tag}@{attr}', val.strip())
                                hc_unit_rows.append(key2)
            except ET.ParseError:
                hc_scene_rows.append(('parse-error', hc_filename))

    total = len(civmods_rows) + len(hc_scene_rows) + len(hc_unit_rows)

    parts = [
        f'<details class="cov-details cov-details-outer">'
        f'<summary class="cov-group-lbl cov-summary-row">'
        f'All art asset references'
        f'<span class="cov-count-pill">{total}</span></summary>'
    ]

    def _render_group(label, rows):
        if not rows:
            return
        parts.append(
            f'<details class="cov-details cov-details-inner">'
            f'<summary class="cov-row cov-bucket-row">'
            f'<span class="cov-lbl">{html_module.escape(label)}</span>'
            f'<span class="cov-count-pill">{len(rows)}</span>'
            f'</summary>'
        )
        for tag, val in rows:
            val_display = val if len(val) <= 80 else "..." + val[-77:]
            parts.append(
                f'<div class="cov-row cov-asset-row">'
                f'<code class="cov-path" style="min-width:160px;flex-shrink:0">'
                f'{html_module.escape(tag)}</code>'
                f'&nbsp;<code class="cov-path cov-asset-path" title="{html_module.escape(val)}">'
                f'{html_module.escape(val_display)}</code>'
                f'</div>'
            )
        parts.append('</details>')

    if not total:
        parts.append('<div class="cov-row"><em class="cov-empty">(none)</em></div>')
    else:
        _render_group("civmods.xml — art fields", civmods_rows)
        _render_group("homecity XML — scene refs", hc_scene_rows)
        _render_group("homecity XML — building/unit refs", hc_unit_rows)

    parts.append('</details>')
    return "".join(parts), total


